package TOPSECRET.persistence.repositoryjpa.datamodel;

import TOPSECRET.domain.ValueObjects.CollectionOfPublicationsId;
import TOPSECRET.domain.ValueObjects.GenreId;
import TOPSECRET.domain.ValueObjects.UserId;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.lang.reflect.Constructor;
import java.lang.reflect.Modifier;
import java.time.LocalDateTime;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.mock;

/**
 * Unit tests for {@link CollectionOfPublicationsDM}.
 *
 * <p>Covers four areas:</p>
 * <ul>
 *   <li><b>Constructor — happy path</b>: verifies successful instantiation
 *       with all valid arguments.</li>
 *
 *   <li><b>Constructor — null rejection</b>: verifies that mandatory fields
 *       ({@code collectionOfPub_id}, {@code collectionName},
 *       {@code genreID}, {@code userId}) throw
 *       {@link NullPointerException} when {@code null}.</li>
 *
 *   <li><b>No-args constructor</b>: verifies that the no-args constructor
 *       generated by Lombok is {@code protected}, reserving it for
 *       JPA internal use only.</li>
 *
 *   <li><b>Getters</b>: verifies that each getter returns the exact value
 *       supplied at construction.</li>
 * </ul>
 */
class CollectionOfPublicationsDMTest {

    private CollectionOfPublicationsId collectionId;
    private String collectionName;
    private GenreId genreId;
    private UserId userId;
    private boolean isPrivate;
    private LocalDateTime publicUntil;

    @BeforeEach
    void setup() {
        collectionId = mock(CollectionOfPublicationsId.class);
        collectionName = "Works by Tolkien";
        genreId = mock(GenreId.class);
        userId = mock(UserId.class);
        isPrivate = true;
        publicUntil = LocalDateTime.now().plusDays(5);
    }

    // =========================================================================
    // Constructor
    // =========================================================================

    @Test
    void constructorShouldInitializeEveryFieldSuccessfully() {

        // Act
        CollectionOfPublicationsDM result =
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                );

        // Assert
        assertNotNull(result);
    }

    @Test
    void shouldThrowExceptionWhenCollectionIdIsNull() {

        //Assert
        assertThrows(NullPointerException.class, () ->
                new CollectionOfPublicationsDM(
                        null,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                ));
    }

    @Test
    void shouldThrowExceptionWhenCollectionNameIsNull() {

        //Assert
        assertThrows(NullPointerException.class, () ->
                new CollectionOfPublicationsDM(
                        collectionId,
                        null,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                ));
    }

    @Test
    void shouldThrowExceptionWhenGenreIdIsNull() {

        //Assert
        assertThrows(NullPointerException.class, () ->
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        null,
                        userId,
                        isPrivate,
                        publicUntil
                ));
    }

    @Test
    void shouldThrowExceptionWhenUserIdIsNull() {

        //Assert
        assertThrows(NullPointerException.class, () ->
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        null,
                        isPrivate,
                        publicUntil
                ));
    }

    @Test
    void noArgConstructorShouldBeProtected() throws NoSuchMethodException {

        //Arrange
        Constructor<CollectionOfPublicationsDM> constructor =
                CollectionOfPublicationsDM.class.getDeclaredConstructor();

        //Act + assert
        assertTrue(Modifier.isProtected(constructor.getModifiers()));
    }

    // =========================================================================
    // Getter
    // =========================================================================

    @Test
    void getCollectionOfPubIdShouldReturnCorrectValue() {

        // Arrange
        CollectionOfPublicationsDM result =
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                );

        // Act + Assert
        assertEquals(collectionId, result.getId());
    }

    @Test
    void getCollectionNameShouldReturnCorrectValue() {

        // Arrange
        CollectionOfPublicationsDM result =
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                );

        // Act + Assert
        assertEquals(collectionName, result.getCollectionName());
    }

    @Test
    void getGenreIdShouldReturnCorrectValue() {

        // Arrange
        CollectionOfPublicationsDM result =
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                );

        // Act + Assert
        assertEquals(genreId, result.getGenreId());
    }

    @Test
    void getUserIdShouldReturnCorrectValue() {

        // Arrange
        CollectionOfPublicationsDM result =
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                );

        // Act + Assert
        assertEquals(userId, result.getOwnerId());
    }

    @Test
    void getIsPrivateShouldReturnCorrectValue() {

        // Arrange
        CollectionOfPublicationsDM result =
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                );

        // Act + Assert
        assertEquals(isPrivate, result.isPrivate());
    }

    @Test
    void isPrivateShouldReturnFalseWhenCollectionGetIsPublic() {

        // Arrange
        boolean isPrivate = false;

        CollectionOfPublicationsDM result =
                new CollectionOfPublicationsDM(
                        collectionId,
                        collectionName,
                        genreId,
                        userId,
                        isPrivate,
                        publicUntil
                );

        // Act + Assert
        assertFalse(result.isPrivate());
    }
}