package TOPSECRET.domain.Country;

import TOPSECRET.domain.ValueObjects.CountryId;

/**
 * Aggregate Root representing a Country in the system.
 * <p>
 * A {@code Country} is uniquely identified by its {@link CountryId}, which is
 * deterministically derived from the country name in uppercase format.
 * This guarantees that the same country name always produces the same identifier.
 * </p>
 * <p>
 * This class enforces basic validation rules on creation, ensuring that only
 * valid countries (as defined in the {@code Countries} enum) can be instantiated.
 * </p>
 * <p>
 * Equality between {@code Country} instances is based solely on their
 * {@link CountryId}, following the principles of Aggregate Root identity.
 * </p>
 */
public class Country {

    private final CountryId _countryId;
    private final String _countryName;

    /**
     * Constructs a new {@code Country} using the provided country name.
     * <p>
     * The constructor validates that the name is not {@code null} or blank,
     * and that it corresponds to a valid constant in the {@code Countries} enum.
     * </p>
     * <p>
     * The {@link CountryId} is automatically generated by converting the
     * country name to uppercase.
     * </p>
     *
     * @param countryName the name of the country;
     *                    must not be {@code null} or blank,
     *                    and must match a valid entry in the {@code Countries} enum
     * @throws IllegalArgumentException if {@code countryName} is {@code null},
     *                                  blank, or not a valid country
     */
    protected Country(String countryName) {

        if (countryName == null || countryName.isBlank()) {
            throw new IllegalArgumentException("Country name cannot be null or blank");
        }

        try {
            TOPSECRET.domain.Enum.Countries.valueOf(countryName.toUpperCase());
        } catch (IllegalArgumentException e) {
            throw new IllegalArgumentException("Country name is not valid");
        }

        this._countryId = new CountryId(countryName.toUpperCase());;
        this._countryName = countryName;
    }

    /**
     * Constructs a {@code Country} with an explicit {@link CountryId}.
     * <p>
     * This constructor is typically used for rehydrating domain objects
     * from persistence layers.
     * </p>
     *
     * @param countryName the name of the country;
     *                    must not be {@code null} or blank
     * @param countryId   the identifier of the country;
     *                    must not be {@code null}
     * @throws IllegalArgumentException if {@code countryName} is {@code null} or blank
     */
    protected Country(String countryName, CountryId countryId) {

        if (countryName == null || countryName.isBlank()) {
            throw new IllegalArgumentException("Country name cannot be null or blank");
        }

        this._countryId = countryId;
        this._countryName = countryName;
    }

    /**
     * Returns the unique identifier of this {@code Country}.
     *
     * @return the {@link CountryId} associated with this country
     */
    public CountryId getCountryID() {
        return _countryId;
    }

    /**
     * Returns the name of this {@code Country}.
     *
     * @return the country name
     */
    public String getCountryName() {
        return _countryName;
    }


    /**
     * Compares this {@code Country} to another object for equality.
     * <p>
     * Two {@code Country} instances are considered equal if they share
     * the same {@link CountryId}, regardless of other attributes.
     * </p>
     *
     * @param object the object to compare with
     * @return {@code true} if the given object is a {@code Country}
     *         with the same {@link CountryId}; {@code false} otherwise
     */
    @Override
    public boolean equals(Object object) {
        if (this == object)
            return true;

        if (object instanceof Country) {
            Country oCountry = (Country) object;

            if (this._countryId.equals(oCountry._countryId))
                return true;
        }
        return false;
    }
}