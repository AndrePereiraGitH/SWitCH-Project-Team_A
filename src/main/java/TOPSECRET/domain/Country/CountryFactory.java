package TOPSECRET.domain.Country;

import org.springframework.stereotype.Component;
import TOPSECRET.domain.ValueObjects.CountryId;

/**
 * Factory responsible for creating {@link Country} aggregate instances.
 * <p>
 * This class centralizes the instantiation logic of {@link Country} objects,
 * ensuring that all required invariants are respected at creation time.
 * </p>
 * <p>
 * It guarantees that each {@link Country} is created with a deterministic
 * {@link CountryId}, derived from the country name in uppercase format.
 * This ensures consistency across the system when representing the same country.
 * </p>
 * <p>
 * Additionally, this factory supports both:
 * <ul>
 *     <li>Creation of new domain instances</li>
 *     <li>Reconstruction of existing instances (e.g., from persistence)</li>
 * </ul>
 * </p>
 */
@Component
public class CountryFactory {


    /**
     * Creates a new {@link Country} with a deterministic {@link CountryId}
     * derived from the provided country name.
     * <p>
     * The {@link CountryId} is internally generated by converting the country name
     * to uppercase, ensuring that identical names always produce the same identifier
     * (e.g., "Portugal" → {@code CountryId("PORTUGAL")}).
     * </p>
     *
     * @param countryName the name of the country to be created;
     *                    must not be {@code null} or blank,
     *                    and must correspond to a valid entry in the {@code Countries} enum
     * @return a new {@link Country} instance
     * @throws IllegalArgumentException if {@code countryName} is {@code null},
     *                                  blank, or not a valid country
     */
    public Country create(String countryName) {
        if (countryName == null || countryName.isBlank()) {
            throw new IllegalArgumentException("Country name cannot be null or blank");
        }
        return new Country(countryName);
    }

    /**
     * Reconstructs an existing {@link Country} using a provided {@link CountryId}
     * and country name.
     * <p>
     * This method is typically used when rehydrating domain objects from
     * persistence layers, where the identifier is already known.
     * </p>
     *
     * @param countryId   the identifier of the country;
     *                    must not be {@code null}
     * @param countryName the name of the country;
     *                    must not be {@code null} or blank
     * @return a reconstructed {@link Country} instance
     * @throws IllegalArgumentException if {@code countryName} is {@code null} or blank,
     *                                  or if {@code countryId} is {@code null}
     */
    public Country create(CountryId countryId, String countryName){
        if (countryName == null || countryName.isBlank()){
            throw new IllegalArgumentException("Country name cannot be null or blank");
        }
        if (countryId == null){
            throw new IllegalArgumentException("Country name cannot be null");
        }

        return new Country(countryName, countryId);
    }
}