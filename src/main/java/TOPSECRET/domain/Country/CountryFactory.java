package TOPSECRET.domain.Country;

import TOPSECRET.domain.ValueObjects.CountryID;

/**
 * Factory responsible for creating {@link Country} aggregate instances.
 * <p>
 * This class handles the instantiation of {@link Country} objects,
 * generating a deterministic {@link CountryID} derived from the country
 * name in uppercase.
 * </p>
 * <p>
 * This ensures that the same country name always produces the same
 * {@link CountryID}, guaranteeing consistency across the system —
 * for example, when multiple users select the same country from a list.
 * </p>
 */
public class CountryFactory {

    /**
     * Creates a new {@link Country} with a deterministic {@link CountryID}
     * derived from the country name.
     * <p>
     * The {@link CountryID} is generated by converting the country name
     * to uppercase, ensuring that the same country always produces the
     * same identifier (e.g., "Portugal" → {@code CountryID("PORTUGAL")}).
     * </p>
     *
     * @param countryName the name of the country to be created;
     *                    must not be {@code null} or blank,
     *                    and must exist in the {@code Countries} enum
     * @return a new {@link Country} instance with a deterministic {@link CountryID}
     * @throws IllegalArgumentException if {@code countryName} is {@code null},
     *                                  blank, or not a valid country in the enum
     */
    public Country create(String countryName) {
        if (countryName == null || countryName.isBlank()) {
            throw new IllegalArgumentException("Country name cannot be null or blank");
        }
        return new Country(countryName);
    }
}